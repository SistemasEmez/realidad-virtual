import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const base='http://localhost:5173';
const login=await fetch(base+'/signin-with-chatgpt?return_to=%2F',{redirect:'manual'});
const cookie=login.headers.getSetCookie().map(c=>c.split(';')[0]).join('; ');
assert.ok(cookie,'Local mock sign-in must provide a cookie');
const headers={Cookie:cookie,Origin:base};
assert.equal((await fetch(base+'/api/experiences')).status,401,'Anonymous records must be denied');
assert.equal((await fetch(base+'/api/files',{method:'POST'})).status,401,'Anonymous uploads must be denied');
const invalidOrigin=await fetch(base+'/api/experiences',{method:'POST',headers:{...headers,Origin:'https://example.com','Content-Type':'application/json'},body:'{}'});
assert.equal(invalidOrigin.status,403,'Foreign origins must be denied');
const bytes=await readFile(new URL('../public/original/Logo1.glb',import.meta.url));
const form=new FormData();form.append('file',new File([bytes],'logo.glb'));
const uploaded=await fetch(base+'/api/files',{method:'POST',headers,body:form});
assert.equal(uploaded.status,200,'GLB upload succeeds');
const {url}=await uploaded.json();
const downloaded=await fetch(base+url,{headers:{Cookie:cookie}});
assert.equal(downloaded.status,200);assert.equal((await downloaded.arrayBuffer()).byteLength,bytes.length);
assert.equal((await fetch(base+url)).status,401,'Anonymous assets must be denied');
assert.equal((await fetch(base+'/api/files/another-user/test.glb',{headers:{Cookie:cookie}})).status,403,'Other users assets must be denied');
const fake=new FormData();fake.append('file',new File(['bad'],'broken.glb'));
assert.equal((await fetch(base+'/api/files',{method:'POST',headers,body:fake})).status,400,'Invalid GLB rejected');
const config={id:crypto.randomUUID(),name:'Verificación local temporal',model:url,target:'/original/targets.mind',brandLogo:'',scale:500,rx:15,ry:30,rz:0,x:.1,y:0,z:0,targetIndex:0,spin:false,modelName:'logo.glb',targetName:'targets.mind'};
assert.equal((await fetch(base+'/api/experiences',{method:'POST',headers:{...headers,'Content-Type':'application/json'},body:JSON.stringify(config)})).status,200);
const rows=await (await fetch(base+'/api/experiences',{headers})).json();
const saved=rows.find(x=>x.id===config.id);assert.equal(saved.scale,500);assert.equal(saved.ry,30);assert.equal(saved.model,url);
assert.equal((await fetch(base+'/api/experiences',{method:'POST',headers:{...headers,'Content-Type':'application/json'},body:JSON.stringify({...config,scale:-1})})).status,400,'Negative scale rejected');
assert.equal((await fetch(base+'/api/experiences?id='+config.id,{method:'DELETE',headers})).status,200);
assert.ok(!(await (await fetch(base+'/api/experiences',{headers})).json()).some(x=>x.id===config.id));
console.log('PASS: authentication, origin checks, GLB validation, upload/download, file ownership, persistence, transformations and deletion.');
