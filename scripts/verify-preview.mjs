import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';

const messages=[], listeners=new Map(), modelListeners=new Map();
const model={style:{},attributes:{},setAttribute(key,value){this.attributes[key]=value},addEventListener(type,handler){modelListeners.set(type,handler)},jumpCameraToGoal(){}};
const status={hidden:false,textContent:'',classList:{toggle(){}}};
let define;
const parent={postMessage(message){messages.push(message)}};
const origin='http://localhost:5173';
const context=vm.createContext({document:{getElementById:id=>id==='model'?model:status},window:{addEventListener(type,handler){listeners.set(type,handler)}},location:{origin},parent,customElements:{whenDefined:()=>new Promise(resolve=>{define=resolve})},setTimeout(){}});
vm.runInContext(await readFile(new URL('../public/preview-controller.js',import.meta.url),'utf8'),context);
const config=(model,modelName)=>({model,modelName,scale:1000,rx:0,ry:0,rz:0,spin:false});
const send=(c,sender=origin)=>listeners.get('message')({origin:sender,source:parent,data:{type:'config',config:c}});
send(config('/first.glb','first.glb'));
send(config('/second.glb','second.glb'));
assert.equal(model.attributes.src,undefined,'Wait for custom element setters');
define();await new Promise(resolve=>setImmediate(resolve));
assert.equal(model.attributes.src,'/second.glb','Retain latest model received before readiness');
assert.ok(messages.some(m=>m.type==='ready'),'Request latest config after initialization');
modelListeners.get('load')();assert.equal(model.style.visibility,'visible');assert.equal(status.hidden,true);
send(config('/replacement.glb','replacement.glb'));
assert.equal(model.attributes.src,'/replacement.glb','Subsequent uploads replace the model without reloading');
assert.equal(model.style.visibility,'hidden','Hide old model while replacement loads');
assert.match(status.textContent,/replacement/);
send(config('/untrusted.glb','untrusted.glb'),'https://example.com');
assert.equal(model.attributes.src,'/replacement.glb','Ignore foreign messages');
modelListeners.get('error')();assert.equal(status.hidden,false);assert.ok(messages.some(m=>m.type==='error'));
console.log('PASS: early config, latest model selection, replacement without reload, loading/error feedback and origin checks.');
